#!/usr/bin/env bash
#
# Write .ai/testing/user-configs-baseline.md: where the golden-master snapshots came from.
#
#   SF_UPDATE_SNAPSHOTS=1 composer test:configs     # generate the snapshots (not in CI)
#   composer test:configs                            # they must pass without the flag
#   bin/generate-baseline.sh                         # record the date, versions and git HEAD
#
# P9 runs this at tag time (v1.0.0). Choose another core with WP_CORE_VERSION (default latest) and another PHP with PHP.
# Only reads the environment; changes nothing but .ai/testing/user-configs-baseline.md.

set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

PHP="${PHP:-php}"
WP_CORE_VERSION="${WP_CORE_VERSION:-latest}"
CORE_DIR="${WP_TESTS_ABSPATH:-${PWD}/.cache/wp-core/${WP_CORE_VERSION}}"

version="$(sed -n "s/^define( 'SWIFTFORMS_VERSION', '\(.*\)' );/\1/p" swiftforms.php)"
wordpress="$(sed -n "s/^\$wp_version = '\(.*\)';/\1/p" "${CORE_DIR}/wp-includes/version.php" 2>/dev/null || true)"
phpunit="$("${PHP}" vendor/phpunit/phpunit/phpunit --version 2>/dev/null | head -1 || true)"
head="$(git rev-parse HEAD 2>/dev/null || echo 'not a git checkout')"
dirty="$(git status --porcelain 2>/dev/null | head -1 || true)"
database="$(mysql -h"${WP_TESTS_DB_HOST:-db}" -u"${WP_TESTS_DB_USER:-root}" -p"${WP_TESTS_DB_PASSWORD:-root}" -N -e 'SELECT VERSION()' 2>/dev/null || echo unknown)"
configs="$(ls tests/user-configs/[0-9][0-9]-*.php | wc -l | tr -d ' ')"

cat >.ai/testing/user-configs-baseline.md <<MD
# Baseline: where the snapshots came from

Generated by \`bin/generate-baseline.sh\` after \`SF_UPDATE_SNAPSHOTS=1 composer test:configs\` (see the README of this folder). The baseline is frozen at the v1.0.0 tag.

| | |
|---|---|
| Date (UTC) | $(date -u +'%Y-%m-%d %H:%M') |
| SwiftForms version | ${version} |
| \`git rev-parse HEAD\` | ${head}$([[ -n "${dirty}" ]] && echo ' (working tree had uncommitted changes)') |
| WordPress | ${wordpress:-unknown} |
| WordPress test library | the core's own (tests/phpunit via WP_TESTS_ABSPATH) |
| PHP | $("${PHP}" -r 'echo PHP_VERSION;') |
| PHPUnit | ${phpunit:-unknown} |
| Database | ${database} |
| Configs | ${configs} |
| Command | \`SF_UPDATE_SNAPSHOTS=1 composer test:configs\` |
MD
echo "Wrote .ai/testing/user-configs-baseline.md"
